ACCESS_CLOSED = "Доступ закрыт. Обратитесь к администратору сервиса."


def private_active(profile_name: str, description: str | None) -> str:
    """Что видит подтверждённый человек, снова нажав /start.

    Не приветствие: он его уже читал. Здесь нужен ответ на вопрос «что про
    меня записано» — и способ это исправить.
    """

    body = escape(description) if description else "пока пусто"
    return (
        f"<b>Профиль: {escape(profile_name)}</b>\n"
        f"{body}\n\n"
        "Заменить описание целиком: <code>/profile_edit</code>.\n"
        "Уточнить отдельные темы: <code>/interests</code>.\n"
        "Как писать профиль: <code>/howto</code>.\n\n"
        "Материалы приходят в группы и каналы, а не сюда."
    )


def approval_message(kind: SubscriberKind | str) -> str:
    """Текст, который уходит подписчику в момент подтверждения."""

    resolved = SubscriberKind(str(getattr(kind, "value", kind)))
    return PRIVATE_APPROVED if resolved is SubscriberKind.USER else CHAT_APPROVED


